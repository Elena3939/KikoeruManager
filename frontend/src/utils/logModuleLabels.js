export function getLogModuleLabel(module) {
  if (Object.hasOwn(MODULE_LABELS, module)) return MODULE_LABELS[module]
  if (module === 'app.core.library_index' || module.startsWith('app.core.library_index.')) return '库存索引'
  if (module === 'app.core.activity_log_aggregator' || module.startsWith('app.core.activity_log_aggregator.')) return '操作历史 · 记录聚合'
  // 未登记的模块保留真实名称，避免错误归类导致排查歧义。
  return module
}
